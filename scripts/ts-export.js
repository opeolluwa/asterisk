#!/usr/bin/env node
/*
Regenerates the frontend TypeScript bindings for Rust types tagged with
#[ts(export)].

Entity types (src/models/*.rs) receive that tag automatically through the
#[macros::ts_rs_export_sea_orm_entity_name] attribute, which derives
ts_rs::TS and renames each exported type to "<Pascal>Interface" (table "admin"
-> "AdminInterface"). Extractors and other DTOs tag themselves directly.

ts-rs emits these bindings from cfg(test) export tests generated by the
#[ts(export)] attribute, so they are produced by running cargo test, not
cargo build. Each type is written to TS_RS_EXPORT_DIR (see .cargo/config.toml,
which points it at typegen/) as <name>.ts.

1. Runs the ts-rs export tests to refresh typegen/*.ts when sources are newer.
2. Generates typegen/index.ts re-exporting every emitted binding.

Usage (from repo root):
    node scripts/ts-export.js [source_dir]

source_dir, used only for the staleness check, defaults to src.
*/

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const ROOT = path.resolve(__dirname, "..");
const BINDINGS_DIR = path.join(ROOT, "typegen");

/** Newest mtime (ms) of files with `ext` under `dir`, or 0 if none. */
function newestMtime(dir, ext, recursive) {
  if (!fs.existsSync(dir)) return 0;

  let newest = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (recursive) newest = Math.max(newest, newestMtime(full, ext, true));
    } else if (entry.name.endsWith(ext)) {
      newest = Math.max(newest, fs.statSync(full).mtimeMs);
    }
  }
  return newest;
}

function updateBindings(sourceDir) {
  const newestSource = newestMtime(sourceDir, ".rs", true);
  const newestBinding = newestMtime(BINDINGS_DIR, ".ts", false);

  if (newestBinding > 0 && newestBinding >= newestSource) return;

  console.log("  running ts-rs export tests (cargo test --lib export_bindings) …");
  fs.mkdirSync(BINDINGS_DIR, { recursive: true });

  execSync("cargo test -p asterisk --lib export_bindings", {
    cwd: ROOT,
    stdio: "inherit",
  });
}

function generateIndex() {
  const header = "// Auto-generated by scripts/ts-export.js — do not edit manually.\n";

  const files = fs
    .readdirSync(BINDINGS_DIR)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .sort();

  const lines = [header, ...files.map((f) => `export * from "./${path.basename(f, ".ts")}";\n`)];

  const indexPath = path.join(BINDINGS_DIR, "index.ts");
  fs.writeFileSync(indexPath, lines.join(""), "utf8");
  console.log(`  wrote: ${indexPath} (${files.length} re-exports)`);
}

function main() {
  const sourceDir = path.resolve(ROOT, process.argv[2] || "src");

  if (!fs.existsSync(sourceDir)) {
    console.error(`error: directory not found: ${sourceDir}`);
    process.exit(1);
  }

  updateBindings(sourceDir);
  generateIndex();
}

main();
